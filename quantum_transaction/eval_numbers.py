"""
Every number Sec. V quotes, printed from the run that produced the figures.
==========================================================================
The section's figures are regenerated by `make_fig_snapshot.py` and
`make_fig_scaling.py`, but several of its sentences quote quantities that no
panel is annotated with -- the sampling distance of the displayed zone laws,
the belief the product of marginals puts on impossible joint choices, the
extra executions the exception re-samples cost.  Reading those off a rendered
panel is how they drifted in the first place.

This module recomputes them from the same seeds, the same partition and the
same protocol call the figures use, so a sentence can be checked against a
printed line rather than against an axis.

Run:  python eval_numbers.py
"""

import numpy as np

from haiq_instance import utility_scale
from haiq_zone import K_ROUNDS, accept_probability
import make_fig_snapshot as snap


def zone_law_distance(rep):
    """TVD between a zone's reported law and its exact accepted law.

    `rep["pref"]` is exp[lambda J_z] normalized on F_z, Eq. (30); the report
    is the weighted empirical law of the retained samples, Eq. (37).  Both are
    over the same enumerated support, so the distance is the sampling error at
    K_z draws and nothing else.
    """
    ref = rep["pref"]
    key = {tuple(int(x) for x in row): t for t, row in enumerate(rep["rows"])}
    meas = np.zeros(len(ref))
    for row, wt in zip(rep["codes"], rep["weights"]):
        meas[key[tuple(int(x) for x in row)]] += wt
    if meas.sum() > 0:
        meas /= meas.sum()
    return 0.5 * float(np.abs(meas - ref).sum())


def impossible_belief(rep):
    """Belief the product of marginals puts on joint choices F_z excludes.

    `snap.strongest_pair` picks the most dependent boundary pair of the zone
    and returns, for every joint choice of that pair, the joint-report
    probability and the product of the two marginals.  A combination that no
    row of F_z realizes is not merely rare -- it violates an owned limit, so
    the product form is asserting something the zone has already ruled out.
    """
    item = snap.strongest_pair(rep)
    if item is None:
        return None
    _, ka, kb, joint, prod = item
    zone, rows = rep["zone"], rep["rows"]
    bad = np.zeros_like(joint, dtype=bool)
    for x in range(joint.shape[0]):
        for y in range(joint.shape[1]):
            bad[x, y] = not ((rows[:, ka] == x) & (rows[:, kb] == y)).any()
    return dict(zone=zone.idx, ue_a=int(zone.ue[ka]), ue_b=int(zone.ue[kb]),
                prod_mass=float(prod[bad].sum()),
                joint_mass=float(joint[bad].sum()))


def execution_overhead(res):
    """Extra executions the exception re-samples cost, as a fraction.

    A zone's initial report costs K_z / P_z(k) executions, Eq. (36).  A
    re-sampled zone pays that again with the commitments pinned, so the
    overhead is the re-sampled zones' share of the region's total.
    """
    reports = [r for r in res["reports"] if r["zone"].n_ue > 0]
    base = sum(r["shots"] for r in reports)
    extra = sum(r["shots"] * n for r, n in zip(reports, res["exc_by_zone"])) \
        if "exc_by_zone" in res else None
    if extra is None:                       # fall back to a flat attribution
        mean = base / max(len(reports), 1)
        extra = mean * res["exceptions"]
    return base, extra, extra / base if base else float("nan")


def main():
    print("=" * 74)
    print(f"  Sec. V numbers, measured at k = {K_ROUNDS} amplification round(s)")
    print("=" * 74)

    (ratio, seed, inst, part, res, opt), peers = snap.pick_seed()
    reports = [r for r in res["reports"] if r["zone"].n_ue > 0]
    ubar = utility_scale(inst)

    print(f"\n[V-C] snapshot instance: g={snap.G} seed={seed}")
    print(f"  APs={inst.n_ap}  UEs={inst.n_ue}  zones={len(reports)}  "
          f"|B|={len(res['holders'])} "
          f"({100.0 * len(res['holders']) / inst.n_ue:.0f}% of UEs)")
    print(f"  utility ratio           {ratio:.2f}% of J*")
    print(f"  peers (16 seeds, g={snap.G}) {len(peers)} feasible, "
          f"{min(peers):.2f}-{max(peers):.2f}%, mean {np.mean(peers):.2f}%")

    d = [zone_law_distance(r) for r in reports]
    shown = snap.pick_zone_panels(reports, snap.N_ZONE_PANELS)
    ds = [zone_law_distance(r) for r in shown]
    print(f"\n[V-B/V-C] sampling distance to the exact accepted law, K_z="
          f"{snap.K_ACCEPT}")
    print(f"  displayed zones Z{[r['zone'].idx for r in shown]}: "
          f"max {max(ds):.3f}, mean {np.mean(ds):.3f}")
    print(f"  all {len(d)} zones:            max {max(d):.3f}, "
          f"mean {np.mean(d):.3f}")

    print(f"\n[V-C] belief on joint choices F_z excludes")
    pairs = [p for p in (impossible_belief(r) for r in reports) if p]
    pairs.sort(key=lambda p: -p["prod_mass"])
    for p in pairs[:2]:
        print(f"  zone Z{p['zone']}, boundary UEs {p['ue_a']} & {p['ue_b']}: "
              f"product of marginals {100 * p['prod_mass']:.0f}%, "
              f"joint report {100 * p['joint_mass']:.0f}%")

    base, extra, frac = execution_overhead(res)
    print(f"\n[V-C] exception re-samples: {res['exceptions']}")
    print(f"  initial executions {base:,.0f}, re-samples add {extra:,.0f} "
          f"({100 * frac:.0f}%)")

    beta_z = [r["beta_z"] for r in reports]
    ess = [r["ess"] for r in reports]
    mu = [r["mu"] for r in reports]
    print(f"\n[V-A] execution exponent and effective sample size")
    print(f"  beta_z          {min(beta_z):.2f} to {max(beta_z):.2f}")
    print(f"  ESS             {min(ess):.0f} of {snap.K_ACCEPT} retained")
    print(f"  P_z(k)/mu_z     {np.mean([accept_probability(m) / m for m in mu]):.1f}x "
          f"(k={K_ROUNDS}); (2k+1)^2 = {(2 * K_ROUNDS + 1) ** 2}")
    print(f"  executions/zone {min(r['shots'] for r in reports):,.0f} to "
          f"{max(r['shots'] for r in reports):,.0f} "
          f"(budget {snap.SHOT_BUDGET:,})")


if __name__ == "__main__":
    main()
